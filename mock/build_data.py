"""Turn the case's test-customers.json into src/data.js (the Worker serves exactly those answers).

    python3 mock/build_data.py <path/to/test-customers.json>
"""
import json
import pathlib
import sys

src = pathlib.Path(sys.argv[1])
d = json.load(open(src, encoding="utf-8"))
out = pathlib.Path(__file__).resolve().parent / "src" / "data.js"
out.write_text("// generated by build_data.py from " + src.name + "; do not edit\nexport const DATA = " + json.dumps(d, ensure_ascii=False) + ";\n", encoding="utf-8")
print(out, len(d.get("customers", [])), "customers", out.stat().st_size, "bytes")
